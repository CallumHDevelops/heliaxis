// Regenerates the Android app's icons from the brand artwork, so they match the website's and
// the iPhone's (public/icon-512.png, apple-touch-icon.png: the same crop of the social profile).
//
//   node scripts/android-icons.mjs
//
// - mipmap-*/ic_launcher.png: the square icon, for Android 7 and older launchers
// - mipmap-*/ic_launcher_background.png + mipmap-anydpi-v26/ic_launcher.xml: the adaptive icon
//   (Android 8+), a wider crop so the launcher's circle, squircle or rounded square shows exactly
//   the square icon's framing, with room to spare at the edges
// - drawable/ic_launcher_monochrome.xml: the spark alone, for Android 13+ themed icons
// - drawable-*/ic_notification_icon.png and public/badge-96.png: the white spark notifications show
// - drawable/splash.png: the gold spark on the charcoal splash screen (colors.xml splashBackground)
// Then release the app (Actions → Android app) so phones pick them up.
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';

const RES = 'android/app/src/main/res';
const PROFILE = 'brand-kit/heliaxis-profile-dark.png'; // 2000px, spark 600–1399
const GOLD = '#F8BC1E';
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

// The square icon is the centred 1244px of the profile, so the spark spans 64% of it.
const ICON_CROP = 1244;
// Adaptive icons are 108dp, of which the launcher shows about the middle 72dp.
const ADAPTIVE_CROP = Math.round((ICON_CROP * 108) / 72);

/** The spark (brand-kit/heliaxis-spark.svg): four monopitch arms, as polygons around (cx, cy). */
function sparkArms(cx, cy, tip) {
  const k = tip / 11.2;
  const arm = [[-1, -2.4], [1, -2.4], [1, -11.2], [-1, -9]];
  const turns = [([x, y]) => [x, y], ([x, y]) => [-y, x], ([x, y]) => [-x, -y], ([x, y]) => [y, -x]];
  const n = (v) => +v.toFixed(3);
  return turns.map((turn) => arm.map((p) => turn(p)).map(([x, y]) => [n(cx + x * k), n(cy + y * k)]));
}

const sparkSvg = (size, tip, fill) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">` +
  sparkArms(size / 2, size / 2, tip)
    .map((pts) => `<polygon fill="${fill}" points="${pts.map((p) => p.join(',')).join(' ')}"/>`)
    .join('') +
  '</svg>';

async function crop(side, size, file) {
  const at = Math.round((2000 - side) / 2);
  await sharp(PROFILE).extract({ left: at, top: at, width: side, height: side }).resize(size, size, { kernel: 'lanczos3' }).png().toFile(file);
}

const svgPng = (svg, file) => sharp(Buffer.from(svg)).png().toFile(file);

for (const [d, x] of Object.entries(DENSITIES)) {
  await mkdir(`${RES}/mipmap-${d}`, { recursive: true });
  await crop(ICON_CROP, 48 * x, `${RES}/mipmap-${d}/ic_launcher.png`);
  await crop(ADAPTIVE_CROP, 108 * x, `${RES}/mipmap-${d}/ic_launcher_background.png`);
  // Same height as the old notification icon: the arms reach 44% of the way across.
  await svgPng(sparkSvg(24 * x, 10.5 * x, '#FFFFFF'), `${RES}/drawable-${d}/ic_notification_icon.png`);
}
await svgPng(sparkSvg(96, 42, '#FFFFFF'), 'public/badge-96.png');
await svgPng(sparkSvg(288, 115, GOLD), `${RES}/drawable/splash.png`);

// The artwork is all in the background layer; the foreground is left clear.
await mkdir(`${RES}/mipmap-anydpi-v26`, { recursive: true });
await writeFile(
  `${RES}/mipmap-anydpi-v26/ic_launcher.xml`,
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@android:color/transparent" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`
);

// Themed icons: the spark the same size as in the square icon (64% of the 72dp the launcher shows).
const path = sparkArms(54, 54, 0.32 * 72)
  .map((pts) => `M${pts.map((p) => p.join(',')).join(' L')} Z`)
  .join(' ');
await writeFile(
  `${RES}/drawable/ic_launcher_monochrome.xml`,
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:pathData="${path}" />
</vector>
`
);
console.log('Android icons written. Release the app (Actions → Android app) to ship them.');
