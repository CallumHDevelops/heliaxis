import type { ProposalOption } from './types';

/**
 * The MCS performance estimate figures, as the design software printed them, in the layout MCS uses: A installation data, B
 * performance calculation, C self-consumption with panels only, D with the battery, E additional benefits. Only the figures the
 * design gave are shown. Pure: the PDF and the web page both draw from it.
 */
export type McsRow = { label: string; value: string; unit: string };
export type McsSection = { title: string; rows: McsRow[] };

const n0 = (x: number) => Math.round(x).toLocaleString('en-GB');
const n1 = (x: number) => (Math.round(x * 10) / 10).toLocaleString('en-GB');
const n2 = (x: number) => (Math.round(x * 100) / 100).toLocaleString('en-GB');

/** 90 → "West (90° from south)"; the sign of the figure is not given by every design, so only the distance is described. */
function direction(deg: number): string {
  const a = Math.abs(deg);
  const word = a < 22.5 ? 'South' : a < 67.5 ? 'South-east or south-west' : a < 112.5 ? 'East or west' : a < 157.5 ? 'North-east or north-west' : 'North';
  return `${word} (${n0(deg)}° from south)`;
}

export function mcsTable(o: ProposalOption): McsSection[] {
  const rows = (xs: (McsRow | null)[]) => xs.filter((x): x is McsRow => !!x);
  const row = (label: string, v: number | string | undefined | null, unit: string, fmt: (n: number) => string = n2): McsRow | null => (v === undefined || v === null || v === '' ? null : { label, value: typeof v === 'number' ? fmt(v) : v, unit });
  const sections: McsSection[] = [
    {
      title: 'A. Installation data',
      rows: rows([
        row('Installed capacity of the PV system (kWp, STC)', o.systemKwp, 'kWp'),
        o.orientationDeg !== undefined ? { label: 'Orientation of the PV system (degrees from south)', value: direction(o.orientationDeg), unit: '' } : null,
        row('Inclination of the system (degrees from horizontal)', o.tiltDeg, '°', n0),
        row('MCS postcode region', o.postcodeRegion, ''),
      ]),
    },
    {
      title: 'B. Performance calculation',
      rows: rows([row('Yield (kWh per kWp, from the MCS table)', o.kwhPerKwp, 'kWh/kWp', n0), row('Shade factor', o.shadeFactor, '', (n) => `${Math.round(n * 1000) / 1000}`), row('Estimated annual output (kWp × yield × shade factor)', o.annualGenerationKwh, 'kWh', n0)]),
    },
    {
      title: 'C. Estimated self-consumption: panels only',
      rows: rows([
        row('Assumed household pattern', o.occupancy, ''),
        row('Assumed annual electricity use', o.consumptionKwh, 'kWh', n0),
        row('Annual electricity generated by the PV system', o.annualGenerationKwh, 'kWh', n0),
        row('Expected solar self-consumption, panels only', o.selfUsePvKwh, 'kWh', n0),
        row('Grid independence (self-sufficiency), panels only', o.selfSufficiencyPvOnlyPct, '%', n1),
      ]),
    },
    {
      title: 'D. Estimated self-consumption: with the battery',
      rows: rows([
        row('Usable capacity of the battery used for self-consumption', o.batteryUsableKwh, 'kWh', n2),
        row('Expected solar self-consumption, with the battery', o.selfUseBatteryKwh, 'kWh', n0),
        row('Grid independence (self-sufficiency), with the battery', o.selfSufficiencyPct, '%', n1),
      ]),
    },
    {
      title: 'E. Additional benefits',
      rows: rows([
        row('Battery capacity not used for self-consumption', o.eessUnusedKwh, 'kWh', n2),
        row('Total energy discharged per year', o.energyDischargedKwh, 'kWh', n0),
        row('Additional self-consumption (EV, heat pump, diverter)', o.extraSelfUseKwh, 'kWh', n0),
      ]),
    },
  ];
  return sections.filter((s) => s.rows.length > 0);
}

/** The words printed with the table, as the design software has them: an estimate by the MCS method, to be read as guidance. */
export const MCS_NOTE =
  'These figures are the MCS performance estimate from the design software, calculated by the standard MCS procedure. They are guidance only, not a guarantee: actual performance may be lower or higher if the installed system differs from the values assumed.';
