/**
 * The proposal pack on a job: what is in it, and what to do when the customer accepts before it is
 * finished. Everything here is best-effort and never throws into the customer's page: a customer who
 * can sign is never stopped by a fault in here (the accept route falls back to the plain signature sheet).
 */

/** The PROPOSAL_PACK switch (off unless set to "on") and whether proposal-pack.sql has been run. */
export async function proposalSwitch(): Promise<{ on: boolean; ready: boolean }> {
  return { on: proposalPackOn(process.env), ready: (await schemaReady()).proposal };
}

/** The job's pack, item by item. */
export async function loadViews(db: Db, projectId: string): Promise<ProposalView[]> {
  const [{ data: project }, { data: docRows }, { data: markRows }, { data: libRows }] = await Promise.all([
    db.from('crm_projects').select('products').eq('id', projectId).maybeSingle(),
    db
      .from('crm_documents')
      .select('id, proposal_slot, name, source, generated_key, visible, created_at, version, inputs_hash')
      .eq('project_id', projectId)
      .not('proposal_slot', 'is', null)
      .is('archived_at', null),
    db.from('proposal_slots').select('slot, na, na_reason, updated_by, updated_at').eq('project_id', projectId),
    // The universal documents (proposal-library.sql): one copy in the library, on every job. Absent before that SQL: none.
    db.from('crm_library').select('id, name, proposal_slot, created_at, archived_at').not('proposal_slot', 'is', null).is('archived_at', null),
  ]);
  const docs: ProposalDoc[] = (docRows ?? []).map((d) => ({
    id: d.id as string,
    slot: d.proposal_slot as string,
    name: d.name as string,
    source: (d.source as string | null) ?? null,
    key: (d.generated_key as string | null) ?? null,
    visible: !!d.visible,
    at: d.created_at as string,
    version: Number(d.version ?? 1),
    hash: (d.inputs_hash as string | null) ?? null,
  }));
  const marks: Partial<Record<string, SlotMark>> = {};
  for (const m of markRows ?? []) marks[m.slot as string] = { na: !!m.na, reason: (m.na_reason as string | null) ?? null, by: (m.updated_by as string | null) ?? null, at: (m.updated_at as string | null) ?? null };
  const lib = libraryDocs((libRows ?? []) as LibraryRow[]);
  const ctx: StateCtx = {
    products: ((project?.products as string[] | null) ?? []).map(String),
    docs: [...docs, ...lib.docs],
    marks,
    // The documents we make ourselves (covering letter, quotation, performance estimate, contract,
    // complaints procedure) are not generated by code yet, so each counts as Missing until they are.
    // That is why the PROPOSAL_PACK switch stays off until the generators ship.
    gen: lib.gen,
    libraryGaps: [],
  };
  return proposalStates(ctx);
}

/** When the customer last pressed Accept with the paperwork unfinished, if they did (null before proposal-pack.sql). */
export async function pendingSince(db: Db, projectId: string): Promise<string | null> {
  const { data } = await db.from('crm_projects').select('accepted_pending_at').eq('id', projectId).maybeSingle();
  return (data?.accepted_pending_at as string | null | undefined) ?? null;
}

type Held = { id: string; enquiry_id: string; owner_id: string | null; title: string };

/**
 * The customer accepted but the pack is not finished. Records it (once: a second tap does nothing and
 * tells nobody again) and returns the alerts to send, to run after the response so the customer
 * is not kept waiting on push notifications. The job stays at Quote sent: only a signature moves it to Won.
 */
export async function holdAcceptance(db: Db, p: Held, o: { ip: string | null; views: ProposalView[]; customer: string }): Promise<{ first: boolean; alert: () => Promise<void> }> {
  const now = new Date().toISOString();
  const { data: held } = await db
    .from('crm_projects')
    .update({ accepted_pending_at: now, accepted_pending_ip: o.ip })
    .eq('id', p.id)
    .is('accepted_pending_at', null)
    .is('accepted_at', null)
    .select('id');
  if (!held?.length) return { first: false, alert: async () => {} };
  const open = openItems(o.views);
  return {
    first: true,
    alert: async () => {
      try {
        await logActivity({
          enquiryId: p.enquiry_id,
          projectId: p.id,
          kind: 'stage',
          body: `Quote accepted online by ${o.customer || 'the customer'}, contract pending: ${open.length} proposal pack ${open.length === 1 ? 'item is' : 'items are'} still open`,
        });
        const { data: people } = await db.from('profiles').select('*').eq('status', 'approved');
        const everyone = (people ?? []) as (Parameters<typeof taskRecipients>[0][number] & Parameters<typeof canAccess>[0])[];
        const recipients = taskRecipients(everyone, p.owner_id);
        const t = gapsTask(o.views, o.customer);
        if (t) await addSourceTask(db, { projectId: p.id, key: t.key, title: t.title, notes: t.notes, assigneeId: taskAssignee(recipients, p.owner_id) });
        const names = open.slice(0, 3).map((v) => v.title).join(', ') + (open.length > 3 ? ` and ${open.length - 3} more` : '');
        await Promise.all(
          recipients.map((userId) =>
            notify({ userId, kind: 'proposal_gaps', title: `Finish the proposal pack: ${p.title}`, body: `${o.customer || 'The customer'} has accepted. The contract can’t go out until this is done: ${names}`, href: `/admin/crm/${p.id}`, tag: `proposal-${p.id}` })
          )
        );
        // The sales team hears it too: a customer has said yes.
        const sales = everyone.filter((x) => canAccess(x, 'crm') && !recipients.includes(x.id));
        await Promise.all(sales.map((x) => notify({ userId: x.id, kind: 'crm_accepted', title: `Quote accepted, contract pending: ${p.title}`, body: 'The customer has accepted online. The proposal pack is still being finished.', href: `/admin/crm/${p.id}`, tag: `crm-${p.id}` })));
      } catch {
        // Best-effort: the acceptance itself is already recorded.
      }
    },
  };
}
