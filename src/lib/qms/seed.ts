/**
 * The standard register Heliaxis works from: a reference, a title and where it is filed. No document text
 * and no revision numbers: each one starts as an empty draft that the checker flags until someone writes it
 * (or "Draft with Claude" does) and an approver signs it off. Where the same ref appeared twice in the
 * source list the second gets "-2".
 */
export type SeedDoc = { kind: DocKind; ref: string; title: string; section?: string; summary?: string; reviewMonths?: number };

